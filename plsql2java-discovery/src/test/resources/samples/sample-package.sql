CREATE OR REPLACE PACKAGE EMP_PKG AS
  PROCEDURE GET_EMPLOYEE(p_id IN NUMBER, p_name OUT VARCHAR2);
  FUNCTION CALC_SALARY(p_id IN NUMBER) RETURN NUMBER;
END EMP_PKG;
/
CREATE OR REPLACE PACKAGE BODY EMP_PKG AS
  PROCEDURE GET_EMPLOYEE(p_id IN NUMBER, p_name OUT VARCHAR2) IS
  BEGIN
    SELECT FIRST_NAME INTO p_name FROM EMPLOYEES WHERE EMPLOYEE_ID = p_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN p_name := NULL;
  END GET_EMPLOYEE;

  FUNCTION CALC_SALARY(p_id IN NUMBER) RETURN NUMBER IS
    v_sal NUMBER;
  BEGIN
    SELECT SALARY INTO v_sal FROM EMPLOYEES WHERE EMPLOYEE_ID = p_id;
    RETURN v_sal;
  END CALC_SALARY;
END EMP_PKG;
/
